def analyze_current():
    """分析当前已有内容"""
    current = {}
    for p in Path("output").rglob("*"):
        if not p.is_dir() or p.name in ["image", "audio"]:
            continue
        parts = str(p.relative_to("output")).split("/")
        if len(parts) >= 2:
            subject = parts[0]
            grade = parts[1]
            key = f"{subject}/{grade}"
            if key not in current:
                current[key] = set()
            current[key].add(parts[2])
    return current

def count_topics():
    """统计当前知识点数量"""
    topics = {}
    for p in Path("output").rglob("*"):
        if not p.is_dir() or p.name in ["image", "audio"]:
            continue
        parts = str(p.relative_to("output")).split("/")
        if len(parts) >= 2:
            key = f"{parts[0]}/{parts[1]}"
            topics[key] = topics.get(key, 0) + 1
    return topics

