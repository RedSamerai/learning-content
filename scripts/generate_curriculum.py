def generate_knowledge_points():
    """生成知识点"""
    kg = []
    item_id = 1
    
    for grade, subjects in CURRICULUM.items():
        for subject, topics in subjects.items():
            for topic in topics:
                # 生成知识点条目
                item = {
                    'id': f"{subject}{grade}{item_id:04d}",
                    'grade': grade,
                    'subject': subject,
                    'topic': topic,
                    'chapter': topic.split('-')[0] if '-' in topic else '基础',
                    'description': f'{grade}{subject}知识点：{topic}',
                    'explanation': '',  # 内容后续补充
                    'example': '',
                    'key_points': ''
                }
                kg.append(item)
                item_id += 1
                
                # 创建文件
                grade_dir = output_dir / grade
                subject_dir = grade_dir / subject
                subject_dir.mkdir(parents=True, exist_ok=True)
                
                # 清理文件名中的非法字符
                safe_topic = topic.replace('/', '-').replace('\\', '-').replace(':', '-').replace('?', '-').replace('*', '').replace('"', '').replace('<', '-').replace('>', '-').replace('|', '-')
                file_name = f"{grade}-{subject}-{safe_topic}.json"
                file_path = subject_dir / file_name
                file_path.write_text(json.dumps(item, ensure_ascii=False, indent=2), encoding='utf-8')
    
    return kg

if __name__ == '__main__':
    kg = generate_knowledge_points()
    
    # 保存知识图谱
    kg_path = base / 'knowledge_graph_complete.json'
    kg_path.write_text(json.dumps(kg, ensure_ascii=False, indent=2), encoding='utf-8')
    
    print(f"知识图谱已生成: {len(kg)}条")
    print(f"文件路径: {kg_path}")
    
    # 统计
    from collections import defaultdict
    by_grade = defaultdict(int)
    for item in kg:
        by_grade[item['grade']] += 1
    
    print("\n各年级知识点数量：")
    for grade, count in sorted(by_grade.items()):
        print(f"  {grade}: {count}课")
