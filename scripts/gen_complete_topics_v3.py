def generate_all_topics():
    all_topics = []
    topic_id = 1
    
    # 小学知识点
    for level, subjects in PRIMARY_TOPICS.items():
        for subject, grades in subjects.items():
            for grade, topics in grades.items():
                for topic in topics:
                    all_topics.append({
                        "id": f"{level[0]}{subject[0]}_{grade.replace('年级','')}_{topic_id}",
                        "grade": grade,
                        "subject": subject,
                        "level": level,
                        "topic": topic
                    })
                    topic_id += 1
    
    # 初中知识点
    for level, subjects in JUNIOR_TOPICS.items():
        for subject, grades in subjects.items():
            for grade, topics in grades.items():
                for topic in topics:
                    all_topics.append({
                        "id": f"{level[0]}{subject[0]}_{grade.replace('年级','')}_{topic_id}",
                        "grade": grade,
                        "subject": subject,
                        "level": level,
                        "topic": topic
                    })
                    topic_id += 1
    
    return all_topics

